using System.Collections.Concurrent;
using System.Net.Http.Json;
using System.Text.Json;

namespace SalonBooking.AssistantApi;

public record EmbeddingInput(string Text, string? Title = null);

public record GeminiTurn(string Model, JsonElement Content);

public static class EmbeddingTask
{
    public const string Document = "RETRIEVAL_DOCUMENT";
    public const string Query = "RETRIEVAL_QUERY";
}

public class GeminiClient(HttpClient httpClient, IConfiguration configuration, ILogger<GeminiClient> logger)
{
    private const string BaseUrl = "https://generativelanguage.googleapis.com/v1beta/models";
    private const int MaxBatchSize = 100;
    private static readonly TimeSpan ModelCooldown = TimeSpan.FromMinutes(2);

    // Static because typed HttpClients are transient; this must outlive a single request.
    private static readonly ConcurrentDictionary<string, DateTimeOffset> CoolingDownUntil = new();

    private string? ApiKey => configuration["Gemini:ApiKey"];

    public bool IsConfigured => !string.IsNullOrWhiteSpace(ApiKey);

    private string EmbeddingModel => configuration["Gemini:EmbeddingModel"] is { Length: > 0 } model
        ? model
        : "gemini-embedding-001";

    private string[] GenerationModels => configuration.GetSection("Gemini:Models").Get<string[]>() is { Length: > 0 } models
        ? models
        : ["gemini-3.8-flash"];

    public async Task<List<float[]>> EmbedAsync(IReadOnlyList<EmbeddingInput> inputs, string taskType, CancellationToken ct = default)
    {
        EnsureConfigured();

        var results = new List<float[]>(inputs.Count);
        foreach (var batch in inputs.Chunk(MaxBatchSize))
        {
            var requestBody = new
            {
                requests = batch.Select(input => new
                {
                    model = $"models/{EmbeddingModel}",
                    content = new { parts = new[] { new { text = input.Text } } },
                    taskType,
                    title = taskType == EmbeddingTask.Document ? input.Title : null,
                    outputDimensionality = KnowledgeChunk.EmbeddingDimensions
                })
            };

            using var doc = await PostAsync($"{BaseUrl}/{EmbeddingModel}:batchEmbedContents", requestBody, ct)
                ?? throw new InvalidOperationException($"Gemini embedding call to {EmbeddingModel} failed.");

            foreach (var embedding in doc.RootElement.GetProperty("embeddings").EnumerateArray())
            {
                var values = embedding.GetProperty("values").EnumerateArray().Select(v => v.GetSingle()).ToArray();
                if (values.Length != KnowledgeChunk.EmbeddingDimensions)
                {
                    throw new InvalidOperationException(
                        $"Expected {KnowledgeChunk.EmbeddingDimensions} dimensions from {EmbeddingModel}, got {values.Length}.");
                }

                results.Add(values);
            }
        }

        return results;
    }

    public async Task<float[]> EmbedQueryAsync(string text, CancellationToken ct = default)
    {
        var embeddings = await EmbedAsync([new EmbeddingInput(text)], EmbeddingTask.Query, ct);
        return embeddings[0];
    }

    public async Task<GeminiTurn?> GenerateContentAsync(object requestBody, string? preferredModel = null, CancellationToken ct = default)
    {
        EnsureConfigured();

        var models = GenerationModels;
        var now = DateTimeOffset.UtcNow;
        var available = models
            .Where(m => !CoolingDownUntil.TryGetValue(m, out var until) || until <= now)
            .ToList();
        if (available.Count == 0)
        {
            available = [models[^1]];
        }

        if (preferredModel is not null && available.Remove(preferredModel))
        {
            available.Insert(0, preferredModel);
        }

        foreach (var model in available)
        {
            using var doc = await PostAsync($"{BaseUrl}/{model}:generateContent", requestBody, ct);
            if (doc is null)
            {
                CoolingDownUntil[model] = DateTimeOffset.UtcNow + ModelCooldown;
                logger.LogInformation("Skipping {Model} for {Minutes} minutes after a failed call.", model, ModelCooldown.TotalMinutes);
                continue;
            }

            CoolingDownUntil.TryRemove(model, out _);

            if (doc.RootElement.TryGetProperty("candidates", out var candidates)
                && candidates.ValueKind == JsonValueKind.Array
                && candidates.GetArrayLength() > 0
                && candidates[0].TryGetProperty("content", out var content)
                && content.TryGetProperty("parts", out var parts)
                && parts.ValueKind == JsonValueKind.Array)
            {
                logger.LogInformation("Assistant turn generated by {Model}", model);
                return new GeminiTurn(model, content.Clone());
            }

            logger.LogWarning("Gemini {Model} returned no usable candidate: {Body}", model, doc.RootElement.GetRawText());
        }

        return null;
    }

    private async Task<JsonDocument?> PostAsync(string url, object body, CancellationToken ct)
    {
        using var request = new HttpRequestMessage(HttpMethod.Post, url)
        {
            Content = JsonContent.Create(body, options: new JsonSerializerOptions(JsonSerializerOptions.Web)
            {
                DefaultIgnoreCondition = System.Text.Json.Serialization.JsonIgnoreCondition.WhenWritingNull
            })
        };
        request.Headers.Add("x-goog-api-key", ApiKey);

        try
        {
            var response = await httpClient.SendAsync(request, ct);
            var raw = await response.Content.ReadAsStringAsync(ct);
            if (!response.IsSuccessStatusCode)
            {
                logger.LogWarning("Gemini call {Url} failed: {StatusCode} {Body}", url, response.StatusCode, raw);
                return null;
            }

            return JsonDocument.Parse(raw);
        }
        catch (Exception ex) when (!ct.IsCancellationRequested)
        {
            logger.LogWarning(ex, "Gemini call {Url} threw.", url);
            return null;
        }
    }

    private void EnsureConfigured()
    {
        if (!IsConfigured)
        {
            throw new InvalidOperationException("Gemini:ApiKey is not configured.");
        }
    }
}
